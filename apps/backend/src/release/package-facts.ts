/** Build facts once; installed copies read the facts sealed by the producer. */
import { readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { isDeepStrictEqual } from 'node:util';
import { releaseKind } from './edition.js';
import { checkNative, packageName, packageVersion, parseTargets, readManifest, type PackageTarget } from './package-closure.js';
import { digest, inventory } from './package-files.js';
import { updateCapabilities } from './update-capabilities.js';

export function packageEnvironment(): NodeJS.ProcessEnv {
  const { NODE_PATH: _path, NODE_OPTIONS: _options, ...env } = process.env;
  return { ...env, PATH: [dirname(process.execPath), env.PATH].filter(Boolean).join(process.platform === 'win32' ? ';' : ':'),
    COREPACK_ENABLE_NETWORK: '0', npm_config_update_notifier: 'false', npm_config_registry: 'http://127.0.0.1:9/', pnpm_config_registry: 'http://127.0.0.1:9/' };
}
/** FORMAT and SCHEMA were generated by buildRelease from this build's executable and SQL assets. */
export function deriveFacts(root: string, targets: PackageTarget[]) {
  const source = readFileSync(join(root, 'SOURCE'), 'utf8').trim();
  if (!/^[a-f0-9]{40}$/.test(source)) throw new Error('Invalid package SOURCE');
  const format = readFileSync(join(root, 'FORMAT'), 'utf8').trim();
  if (!/^[a-f0-9]{64}$/.test(format)) throw new Error('Invalid package FORMAT');
  const schema = JSON.parse(readFileSync(join(root, 'SCHEMA.json'), 'utf8'));
  const skills = inventory(join(root, 'skills'));
  if (!Object.hasOwn(skills, 'alpacawork/SKILL.md')) throw new Error('Missing managed alpacawork skill');
  checkNative(root, targets);
  return { source, edition: releaseKind(root), format, schema,
    skills: { sha256: digest(JSON.stringify(skills)) }, targets, update: updateCapabilities() };
}
export type PackageFacts = ReturnType<typeof deriveFacts>;

/** npm integrity owns content verification. Copies never execute or re-derive candidate code. */
export function validatePackage(root: string, expected?: PackageFacts): PackageFacts {
  const pkg = readManifest(root); packageName(pkg.name);
  if (pkg.private) throw new Error('Invalid distribution identity');
  try { packageVersion(pkg.version); } catch { throw new Error('Invalid distribution identity'); }
  // Require the producer's inventory, without reading every listed file again.
  const recorded = JSON.parse(readFileSync(join(root, 'DISTRIBUTION.json'), 'utf8'));
  if (!recorded || typeof recorded !== 'object' || Array.isArray(recorded)) throw new Error('Missing distribution inventory');
  const facts = pkg.alpacawork as PackageFacts;
  if (!facts || !Array.isArray(facts.targets) || !/^[a-f0-9]{40}$/.test(facts.source) || !/^[a-f0-9]{64}$/.test(facts.format))
    throw new Error('Missing distribution facts');
  parseTargets(facts.targets.join(','));
  if (facts.source !== readFileSync(join(root, 'SOURCE'), 'utf8').trim() ||
      facts.format !== readFileSync(join(root, 'FORMAT'), 'utf8').trim() || facts.edition !== releaseKind(root) ||
      !isDeepStrictEqual(facts.schema, JSON.parse(readFileSync(join(root, 'SCHEMA.json'), 'utf8'))) ||
      expected && !isDeepStrictEqual(expected, facts)) throw new Error('Package SOURCE/edition/FORMAT/SCHEMA/targets mismatch');
  return facts;
}
