import { isDeepStrictEqual } from 'node:util';
import { withResources } from './resource-scope.js';
/** Write-once messages: publication keeps existing records and readers see complete bytes. */
import { randomUUID, createHash } from 'node:crypto';
import { closeSync, constants, fstatSync, fsyncSync, openSync, readSync, writeSync, mkdirSync, linkSync, unlinkSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { hasCode } from './errors.js';

export const digestBytes = (bytes: Uint8Array | string) => createHash('sha256').update(bytes).digest('hex');
const scratchPrefix = 'tmp-';
/** Only the unpublished names generated by this publisher, never arbitrary prefix matches or records. */
export const isImmutableScratchName = (name: string): boolean => name.startsWith(scratchPrefix) &&
  /^[a-f0-9]{8}-[a-f0-9]{4}-4[a-f0-9]{3}-[89ab][a-f0-9]{3}-[a-f0-9]{12}$/.test(name.slice(scratchPrefix.length));
const basename = (name: string) => {
  if (!/^[A-Za-z0-9][A-Za-z0-9_.-]*$/.test(name)) throw new Error(`Unsafe message name: ${name}`);
};
export function readImmutable(path: string, name: string, limit: number): Buffer {
  basename(name);
  const fd = openSync(join(path, name), constants.O_RDONLY);
  try { return readImmutableFd(fd, limit); } finally { closeSync(fd); }
}
/** Read a borrowed file without moving its offset or releasing the caller's lock. */
export function readImmutableFd(fd: number, limit: number): Buffer {
  if (!Number.isSafeInteger(limit) || limit < 0) throw new Error('Invalid immutable read limit');
  if (fstatSync(fd).size > limit) throw new Error('Oversized immutable message');
  const bytes = Buffer.alloc(limit + 1);
  let n = 0;
  while (n < bytes.length) { const got = readSync(fd, bytes, n, bytes.length - n, n); if (!got) break; n += got; }
  if (n > limit) throw new Error('Oversized immutable message');
  return bytes.subarray(0, n);
}
export class ImmutableConflict extends Error {
  constructor(readonly path: string, readonly entry: string) { super(`Immutable message conflict: ${entry}`); }
}
export class ImmutableSaveUnconfirmed extends Error {
  readonly errors: readonly unknown[];
  constructor(readonly path: string, readonly entry: string, cause: unknown) {
    super(`Immutable publication is unconfirmed: ${entry}`, { cause });
    this.errors = cause instanceof AggregateError ? [...cause.errors] : [cause];
  }
}
/** Completed files are published without replacing an existing business record. */
function publish(path: string, name: string, bytes: Buffer, limit: number, equal: (read: Buffer) => boolean): void {
  basename(name);
  const temporary = join(path, scratchPrefix + randomUUID());
  try { withResources(resources => {
    mkdirSync(path, { recursive: true, mode: 0o700 });
    const parent = openSync(dirname(path), constants.O_RDONLY | constants.O_DIRECTORY);
    try { fsyncSync(parent); } finally { closeSync(parent); }
    const dir = openSync(path, constants.O_RDONLY | constants.O_DIRECTORY); resources.defer(() => closeSync(dir));
    const fd = openSync(temporary, constants.O_WRONLY | constants.O_CREAT | constants.O_EXCL, 0o600);
    resources.defer(() => { try { unlinkSync(temporary); } catch (error) { if (!hasCode(error, 'ENOENT')) throw error; } });
    withResources(file => {
      file.defer(() => closeSync(fd));
      let offset = 0;
      while (offset < bytes.length) { const n = writeSync(fd, bytes, offset); if (!n) throw new Error('No write progress'); offset += n; }
      fsyncSync(fd);
    });
    try { linkSync(temporary, join(path, name)); }
    catch (error) { if (!hasCode(error, 'EEXIST')) throw error; }
    unlinkSync(temporary);
    const destination = openSync(join(path, name), constants.O_RDONLY); resources.defer(() => closeSync(destination));
    if (fstatSync(destination).size > limit) throw new ImmutableConflict(path, name);
    if (!equal(readImmutableFd(destination, limit))) throw new ImmutableConflict(path, name);
    fsyncSync(destination);
    fsyncSync(dir);
  }); } catch (error) {
    if (error instanceof ImmutableConflict) throw error;
    throw new ImmutableSaveUnconfirmed(path, name, error);
  }
}
export function publishImmutable(path: string, name: string, data: Uint8Array | string): void {
  const bytes = Buffer.from(data);
  // Read one extra byte so a longer prior input is an immutable conflict too.
  publish(path, name, bytes, Math.max(bytes.length + 1, 1), read => read.equals(bytes));
}
export function publishImmutableJson(path: string, name: string, value: unknown, limit: number): void {
  const bytes = Buffer.from(JSON.stringify(value) + '\n');
  if (bytes.length > limit) throw new Error('Oversized immutable JSON');
  publish(path, name, bytes, limit, read => isDeepStrictEqual(JSON.parse(read.toString('utf8')), value));
}
